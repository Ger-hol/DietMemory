create table if not exists public.cele (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  osoba text not null unique,
  kalorie double precision not null default 0,
  weglowodany_procent double precision not null default 0,
  bialko_procent double precision not null default 0,
  tluszcz_procent double precision not null default 0,
  weglowodany_gram double precision not null default 0,
  bialko_gram double precision not null default 0,
  tluszcz_gram double precision not null default 0,
  data_obliczenia date
);
alter table public.cele enable row level security;
grant select, insert, update, delete on public.cele to authenticated;
revoke all on public.cele from anon;
drop policy if exists "Zalogowani zarzadzaja celami" on public.cele;
create policy "Zalogowani zarzadzaja celami" on public.cele for all to authenticated using (true) with check (true);
